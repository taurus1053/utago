package com.utago.content;

/**
 * 곡의 공개 범위.
 * PRIVATE - 등록한 사용자 본인만 볼 수 있음 (직접 타이핑한 가사 등, 라이선스 없는 콘텐츠 기본값).
 * PUBLIC  - 모든 사용자에게 공개되는 정식 카탈로그. 저작권 문제가 해결된 곡만 이 상태가 되어야 한다
 *           (전통/동요, 라이선스 확보 곡, 아티스트 개별 허락을 받은 곡 등) — 운영진이 직접 올리거나
 *           승격시키는 것을 전제로 하며, 사용자가 등록한 곡은 절대 자동으로 PUBLIC이 되지 않는다.
 */
public enum Visibility {
    PRIVATE,
    PUBLIC
}
